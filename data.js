function getClinicCoordinates(clinic) {
  if (!clinic) return { latitude: null, longitude: null };
  var lat = clinic.latitude != null ? Number(clinic.latitude) : null;
  var lng = clinic.longitude != null ? Number(clinic.longitude) : null;
  return {
    latitude: Number.isFinite(lat) ? lat : null,
    longitude: Number.isFinite(lng) ? lng : null,
  };
}

function clinicServiceLabel(service) {
  if (typeof service === 'string') return service;
  if (service && typeof service === 'object') {
    return service.label || service.name || '';
  }
  return '';
}

function clinicHasRealImage(clinic) {
  var img = clinic && clinic.image ? String(clinic.image).trim() : '';
  return img.length > 0 && !/clinic-placeholder/i.test(img);
}

function sortNahalFirst(clinics) {
  return clinics.slice().sort(function (a, b) {
    if (a.id === NAHAL_CLINIC_ID) return -1;
    if (b.id === NAHAL_CLINIC_ID) return 1;
    return 0;
  });
}

function clinicsForDisplay(clinics) {
  return sortNahalFirst(clinics.filter(clinicHasRealImage));
}
