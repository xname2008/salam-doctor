var NAHAL_CLINIC_ID = 114;

/**
 * Normalize clinic.services entries.
 * Supports legacy plain strings and structured { label, slug, url } tags.
 * Landing URL defaults to /services/<slug>.
 */
function normalizeClinicService(item) {
  if (item == null) return null;
  if (typeof item === 'string') {
    var label = item.trim();
    if (!label || label === 'دارد') return null;
    var slug = label
      .toLowerCase()
      .replace(/[^\w\u0600-\u06FF]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 80);
    return { label: label, slug: slug, url: '/services/' + encodeURIComponent(slug) };
  }
  if (typeof item !== 'object') return null;
  var name = (item.label || item.name || item.title || '').trim();
  if (!name) return null;
  var s = (item.slug || '').trim();
  var u = (item.url || '').trim();
  if (!s && u.indexOf('/services/') === 0) {
    s = u.replace(/^\/services\//, '').split(/[?#]/)[0];
  }
  if (!s) {
    s = name
      .toLowerCase()
      .replace(/[^\w\u0600-\u06FF]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 80);
  }
  if (!u) u = '/services/' + encodeURIComponent(s);
  return { label: name, slug: s, url: u };
}

function normalizeClinicServices(services) {
  if (!Array.isArray(services)) return [];
  var out = [];
  var seen = {};
  for (var i = 0; i < services.length; i += 1) {
    var tag = normalizeClinicService(services[i]);
    if (!tag) continue;
    var key = tag.slug || tag.label;
    if (seen[key]) continue;
    seen[key] = true;
    out.push(tag);
  }
  return out;
}

